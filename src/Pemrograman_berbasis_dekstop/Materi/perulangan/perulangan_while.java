package Pemrograman_berbasis_dekstop.Materi.perulangan;

public class perulangan_while {
    public static void main(String[] args) {
        int i = 1;
        while (i < 9) {
            System.out.println("nilai x 1");
            i++;
        }
        int j = 1;
        do {
            System.out.println("nilai x 300");
            j++;
        } while (j < 9);
    }

}
